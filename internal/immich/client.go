// Package immich is a minimal client for the parts of the Immich HTTP API that
// immich-courier needs. It is written from the public API, not generated from
// or copied out of the Immich codebase.
package immich

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"strings"
	"time"
)

// Client talks to one Immich server. Exactly one of APIKey or AccessToken is
// normally set; with neither, only unauthenticated endpoints work. Headers
// (validated with ValidateHeaders) go with every request, ping included.
type Client struct {
	BaseURL     string // e.g. https://photos.example.com (no trailing /api)
	APIKey      string
	AccessToken string
	Headers     []Header
	HTTP        *http.Client
}

func New(baseURL string) *Client {
	return &Client{
		BaseURL: strings.TrimRight(baseURL, "/"),
		HTTP:    &http.Client{Timeout: 30 * time.Second, CheckRedirect: sameOrigin},
	}
}

// sameOrigin refuses redirects that leave the server's scheme and host. The
// API key and any custom headers are forwarded by net/http on every redirect, so
// a redirect to another host (an SSO gateway, a misconfigured proxy) or to
// plain http would hand the key over.
func sameOrigin(req *http.Request, via []*http.Request) error {
	orig := via[0].URL
	if req.URL.Scheme != orig.Scheme || req.URL.Host != orig.Host {
		return fmt.Errorf("immich: the server redirected to %s://%s; not following it with your credentials (check the server address)", req.URL.Scheme, req.URL.Host)
	}
	if len(via) >= 10 {
		return errors.New("immich: too many redirects")
	}
	return nil
}

// APIError is a non-2xx response from Immich.
type APIError struct {
	Status  int
	Message string
}

func (e *APIError) Error() string {
	return fmt.Sprintf("immich: HTTP %d: %s", e.Status, e.Message)
}

func (c *Client) do(ctx context.Context, method, path string, in, out any) error {
	var body io.Reader
	if in != nil {
		b, err := json.Marshal(in)
		if err != nil {
			return err
		}
		body = bytes.NewReader(b)
	}
	req, err := http.NewRequestWithContext(ctx, method, c.BaseURL+"/api"+path, body)
	if err != nil {
		return err
	}
	if in != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	req.Header.Set("Accept", "application/json")
	c.authorize(req)

	resp, err := c.HTTP.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return err
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		var e struct {
			Message any `json:"message"`
		}
		msg := strings.TrimSpace(string(data))
		if json.Unmarshal(data, &e) == nil && e.Message != nil {
			msg = fmt.Sprint(e.Message)
		}
		return &APIError{Status: resp.StatusCode, Message: msg}
	}
	if out != nil && len(data) > 0 {
		return json.Unmarshal(data, out)
	}
	return nil
}

// Ping returns nil if the server answers /api/server/ping. It is the only
// call used for reachability checks.
func (c *Client) Ping(ctx context.Context) error {
	var r struct {
		Res string `json:"res"`
	}
	// Ping needs no Immich credentials; don't send them. Custom headers
	// stay: a proxy in front of Immich may refuse anything without them.
	anon := *c
	anon.APIKey, anon.AccessToken = "", ""
	if err := anon.do(ctx, http.MethodGet, "/server/ping", nil, &r); err != nil {
		return err
	}
	if r.Res != "pong" {
		return fmt.Errorf("immich: unexpected ping response %q", r.Res)
	}
	return nil
}

type Features struct {
	OAuth         bool `json:"oauth"`
	PasswordLogin bool `json:"passwordLogin"`
}

func (c *Client) Features(ctx context.Context) (Features, error) {
	var f Features
	err := c.do(ctx, http.MethodGet, "/server/features", nil, &f)
	return f, err
}

type Version struct {
	Major int `json:"major"`
	Minor int `json:"minor"`
	Patch int `json:"patch"`
}

func (v Version) String() string { return fmt.Sprintf("%d.%d.%d", v.Major, v.Minor, v.Patch) }

func (c *Client) Version(ctx context.Context) (Version, error) {
	var v Version
	err := c.do(ctx, http.MethodGet, "/server/version", nil, &v)
	return v, err
}

// LoginResponse is returned by both password and OAuth login. AccessToken is
// a user session token.
type LoginResponse struct {
	AccessToken string `json:"accessToken"`
	UserID      string `json:"userId"`
	UserEmail   string `json:"userEmail"`
	Name        string `json:"name"`
}

func (c *Client) PasswordLogin(ctx context.Context, email, password string) (LoginResponse, error) {
	var r LoginResponse
	err := c.do(ctx, http.MethodPost, "/auth/login",
		map[string]string{"email": email, "password": password}, &r)
	return r, err
}

// OAuthAuthorize asks Immich for the identity provider's authorization URL.
// state and codeChallenge are generated by the caller (PKCE, S256).
func (c *Client) OAuthAuthorize(ctx context.Context, redirectURI, state, codeChallenge string) (string, error) {
	var r struct {
		URL string `json:"url"`
	}
	err := c.do(ctx, http.MethodPost, "/oauth/authorize", map[string]string{
		"redirectUri":   redirectURI,
		"state":         state,
		"codeChallenge": codeChallenge,
	}, &r)
	return r.URL, err
}

// OAuthCallback exchanges the full callback URL (with code and state) for an
// Immich session.
func (c *Client) OAuthCallback(ctx context.Context, callbackURL, state, codeVerifier string) (LoginResponse, error) {
	var r LoginResponse
	err := c.do(ctx, http.MethodPost, "/oauth/callback", map[string]string{
		"url":          callbackURL,
		"state":        state,
		"codeVerifier": codeVerifier,
	}, &r)
	return r, err
}

// Logout ends the current session (AccessToken).
func (c *Client) Logout(ctx context.Context) error {
	return c.do(ctx, http.MethodPost, "/auth/logout", nil, nil)
}

type APIKey struct {
	ID          string   `json:"id"`
	Name        string   `json:"name"`
	Permissions []string `json:"permissions"`
	Secret      string   `json:"-"`
}

// CreateAPIKey creates an API key for the logged-in user with the given
// permissions and returns it, including the secret (only shown once).
func (c *Client) CreateAPIKey(ctx context.Context, name string, permissions []string) (APIKey, error) {
	var r struct {
		Secret string `json:"secret"`
		APIKey APIKey `json:"apiKey"`
	}
	err := c.do(ctx, http.MethodPost, "/api-keys", map[string]any{
		"name":        name,
		"permissions": permissions,
	}, &r)
	r.APIKey.Secret = r.Secret
	return r.APIKey, err
}

type User struct {
	ID    string `json:"id"`
	Email string `json:"email"`
	Name  string `json:"name"`
}

func (c *Client) Me(ctx context.Context) (User, error) {
	var u User
	err := c.do(ctx, http.MethodGet, "/users/me", nil, &u)
	return u, err
}
